// Writes lib/features/tour/tour_highlights.dart from the rectangles that
// render_tour_test.dart measured (CHEESE-49). Run by
// tool/visual/build_tour_assets.sh; by hand:
//
//   dart run tool/visual/write_tour_highlights.dart <render-out>/rects
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: write_tour_highlights.dart <rects dir>');
    exit(64);
  }
  final files =
      Directory(args.single)
          .listSync()
          .whereType<File>()
          .where((f) => f.path.endsWith('.json'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  if (files.isEmpty) {
    stderr.writeln('No rectangles in ${args.single}');
    exit(1);
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/visual/build_tour_assets.sh from the')
    ..writeln('// widgets render_tour_test.dart measured. Do not edit.')
    ..writeln()
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln("/// Each tour frame's highlights, as fractions of the picture.")
    ..writeln('const tourHighlights = <String, List<Rect>>{');
  for (final f in files) {
    final id = f.uri.pathSegments.last.replaceAll('.json', '');
    final rects = (jsonDecode(f.readAsStringSync()) as List)
        .cast<List<dynamic>>();
    out.writeln("  '$id': [");
    for (final r in rects) {
      out.writeln('    Rect.fromLTWH(${r.join(', ')}),');
    }
    out.writeln('  ],');
  }
  out.writeln('};');
  File('lib/features/tour/tour_highlights.dart').writeAsStringSync('$out');
}
