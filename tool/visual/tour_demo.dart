TastingNote _note(
  String id,
  String name,
  DateTime day, {
  required String style,
  String? creamery,
  String? origin,
  MilkType milk = MilkType.cow,
  RindType? rind,
  bool raw = false,
  bool grassfed = false,
  int rating = 0,
  TextureLevel texture = TextureLevel.semiSoft,
  Map<FlavorNote, int> flavors = const {},
  double? price,
  String? verdict,
}) => TastingNote(
  id: id,
  cheeseName: name,
  tastedAt: day,
  createdAt: DateTime.utc(day.year, day.month, day.day, 19),
  creamery: creamery,
  origin: origin,
  milk: milk,
  rind: rind,
  isRaw: raw,
  isGrassfed: grassfed,
  rating: rating,
  texture: texture,
  flavors: flavors,
  price: price,
  verdict: verdict,
  cheeseStyleId: style,
);

